//! The proportional desktop font (spec 0015).
//!
//! This is a 12-pixel-tall bitmap font for printable ASCII (`0x20..=0x7E`) with
//! a **variable advance** per glyph. The line box is 12 rows: caps occupy rows
//! 2..=9, the baseline is row 9, lowercase x-height is rows 4..=9, ascenders
//! start at row 1 and descenders reach row 11. Stems are one pixel and the
//! letterforms use squared ranges; the whole set is meant to read like a small
//! Chicago-style system font at 1×, not a scaled text face.
//!
//! # Source table and glyph cache
//!
//! [`SOURCE`] is the font's definition as 10-column ASCII art, one string per
//! printable byte, plus the glyph's advance width. Rendering a glyph means
//! turning those columns into one `u16` bitmask per row, trimming the ink
//! bounds and caching both. [`CACHE`] is a fixed array of 95 optional
//! [`Glyph`]s behind one spin lock: no allocation, no lazy static, and the
//! first draw (or metric query, or the boot self-check) fills it for the rest
//! of the system's life.
//!
//! Lock order: the graphics module holds `SCREEN` and calls [`glyph`], so the
//! order is `SCREEN → FONT`. Nothing takes the font cache and then the screen,
//! so there is no cycle. [`text_width`] and [`self_check`] take only the font
//! lock.
//!
//! # Coverage and fallback
//!
//! Only `0x20..=0x7E` is proportional. Every other byte keeps the 8×8 console
//! font's cell with an 8-pixel advance in [`crate::gfx::draw_text_prop`]; bytes
//! at or above `0x80` have no 8×8 glyph and draw a blank 8×8 cell. This keeps
//! multi-byte text from faulting and gives a documented, deterministic width.

use crate::sync::SpinLock;

/// Height of one line box in pixels (the font's line height).
pub const LINE_HEIGHT: u16 = 12;

/// The baseline row inside the line box (0-based from the top).
pub const BASELINE: u16 = 9;

/// Rows stored per rendered glyph.
pub const GLYPH_ROWS: usize = 12;

/// Columns of ASCII art per glyph.
pub const GLYPH_COLS: usize = 10;

/// Advance used by the 8×8 fallback for a byte outside the proportional set.
pub const FALLBACK_ADVANCE: u16 = 8;

/// First byte with a proportional glyph (`' '`).
pub const FIRST: u8 = 0x20;

/// Last byte with a proportional glyph (`'~'`).
pub const LAST: u8 = 0x7E;

/// Number of proportional glyphs.
pub const COUNT: usize = (LAST - FIRST + 1) as usize;

/// One glyph's definition: its advance and its 10-column ASCII-art rows.
///
/// The rows are separated by `\n`; `.` is off and `#` is on. Every glyph has
/// exactly [`GLYPH_ROWS`] rows of [`GLYPH_COLS`] columns.
pub struct Source {
    /// Advance in pixels, including the right bearing.
    pub advance: u16,
    /// The ASCII art, ignored bytes other than `.`, `#` and `\n`.
    pub art: &'static str,
}

/// One rendered glyph, held in the cache.
#[derive(Clone, Copy)]
pub struct Glyph {
    /// Total advance in pixels.
    pub advance: u16,
    /// Leftmost inked column inside the 10-column box.
    pub left: u16,
    /// Width of the inked columns.
    pub width: u16,
    /// One bitmask per row; bit 0 is the leftmost column.
    pub rows: [u16; GLYPH_ROWS],
}

struct Cache {
    slots: [Option<Glyph>; COUNT],
}

static CACHE: SpinLock<Cache> = SpinLock::new(Cache {
    slots: [None; COUNT],
});

/// Renders a source definition into a [`Glyph`].
///
/// Malformed art cannot panic: pixels beyond the row or column bounds are
/// dropped, and the boot [`self_check`] reports the shape error before any
/// application draws.
fn render(source: &Source) -> Glyph {
    let mut rows = [0u16; GLYPH_ROWS];
    let mut row = 0usize;
    let mut col = 0usize;
    for byte in source.art.bytes() {
        match byte {
            b'.' => col += 1,
            b'#' => {
                if row < GLYPH_ROWS && col < GLYPH_COLS {
                    rows[row] |= 1u16 << col;
                }
                col += 1;
            }
            b'\n' => {
                row += 1;
                col = 0;
            }
            // Indentation or comments around the art are ignored.
            _ => {}
        }
    }

    let mut left = GLYPH_COLS as u16;
    let mut right = 0u16;
    for bits in rows {
        if bits != 0 {
            let low = bits.trailing_zeros() as u16;
            let high = (u16::BITS - 1 - bits.leading_zeros()) as u16;
            left = left.min(low);
            right = right.max(high);
        }
    }
    if left > right {
        // No ink (space and the control fallbacks).
        left = 0;
        right = 0;
    } else {
        right += 1;
    }
    Glyph {
        advance: source.advance,
        left,
        width: right.saturating_sub(left),
        rows,
    }
}

/// The rendered glyph for a printable ASCII byte, or `None` outside
/// `0x20..=0x7E`. The first call for a byte renders and caches it.
pub fn glyph(byte: u8) -> Option<Glyph> {
    if !(FIRST..=LAST).contains(&byte) {
        return None;
    }
    let index = usize::from(byte - FIRST);
    let mut cache = CACHE.lock();
    if let Some(glyph) = cache.slots[index] {
        return Some(glyph);
    }
    let glyph = render(&SOURCE[index]);
    cache.slots[index] = Some(glyph);
    Some(glyph)
}

/// The advance of one byte: the proportional width for printable ASCII, the
/// 8×8 fallback width otherwise.
pub fn advance(byte: u8) -> u16 {
    match glyph(byte) {
        Some(glyph) => glyph.advance,
        None => FALLBACK_ADVANCE,
    }
}

/// The advance width of a byte string, in pixels.
pub fn text_width(text: &[u8]) -> u64 {
    text.iter().map(|byte| u64::from(advance(*byte))).sum()
}

/// Checks that every glyph is well formed and that the font's advertised
/// metrics hold. Used by the boot self-check; returns the failing step.
pub fn self_check() -> Result<(), u32> {
    if SOURCE.len() != COUNT {
        return Err(1);
    }
    for (index, source) in SOURCE.iter().enumerate() {
        if !art_is_well_formed(source.art) {
            return Err(2 + index as u32);
        }
        let glyph = render(source);
        if glyph.advance < glyph.width || glyph.advance == 0 || glyph.advance > 12 {
            return Err(200 + index as u32);
        }
        if glyph.left + glyph.width > GLYPH_COLS as u16 {
            return Err(300 + index as u32);
        }
    }
    // Every printable byte renders; the two ends of the range map to real
    // glyphs and the bytes around them do not.
    if glyph(FIRST).is_none() || glyph(LAST).is_none() {
        return Err(400);
    }
    if glyph(FIRST - 1).is_some() || glyph(LAST + 1).is_some() {
        return Err(401);
    }
    if text_width(b"") != 0 {
        return Err(402);
    }
    if text_width(b"i") >= text_width(b"M") {
        return Err(403);
    }
    if text_width(b"ii") >= text_width(b"WW") || text_width(b"Wi") <= text_width(b"ii") {
        return Err(404);
    }
    // The fallback is eight pixels per byte, including each UTF-8 byte of a
    // non-ASCII code point.
    if text_width(b"A") + 2 * u64::from(FALLBACK_ADVANCE) != text_width(b"A\xC3\xA9") {
        return Err(405);
    }
    if LINE_HEIGHT != 12 || BASELINE != 9 {
        return Err(406);
    }
    Ok(())
}

/// True when the art has exactly [`GLYPH_ROWS`] rows of [`GLYPH_COLS`] cells.
fn art_is_well_formed(art: &str) -> bool {
    let mut rows = 0usize;
    let mut col = 0usize;
    for byte in art.bytes() {
        match byte {
            b'.' | b'#' => col += 1,
            b'\n' => {
                if col != GLYPH_COLS {
                    return false;
                }
                rows += 1;
                col = 0;
            }
            _ => {}
        }
    }
    if col == GLYPH_COLS {
        rows += 1;
    }
    rows == GLYPH_ROWS && col == GLYPH_COLS
}

